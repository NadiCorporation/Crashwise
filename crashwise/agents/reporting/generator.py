"""AI Report Synthesizer — generates professional vulnerability disclosure
reports and structured finding models from crash data, RCA, and verification results.

Supports multiple output formats tailored to specific platforms:
    • ``hackerone`` — HackerOne markdown with impact & reproduction steps.
    • ``bugcrowd`` — Bugcrowd template with severity justification.
    • ``kernel`` — Linux kernel mailing list style (plain text, technical).
    • ``generic`` — Platform-agnostic Markdown suitable for any tracker.

Also provides structured finding generation (:func:`generate_finding_report`)
exporting type-safe :class:`FindingReport` models containing bug class, affected
function, source location (file:line), crash input SHA256 hash, and 4-tier severity.
"""

from __future__ import annotations

import contextlib
import hashlib
import re
from pathlib import Path
from typing import Any

from crashwise.agents.triage.analyzer import classify_crash_severity
from crashwise.core.ai_provider import get_provider
from crashwise.core.logging import get_logger
from crashwise.core.models import (
    CrashSeverity,
    FindingReport,
    FindingReproductionMetadata,
)

log = get_logger(__name__)

